import assert from "node:assert/strict";
import { mkdtempSync, rmSync } from "node:fs";
import os from "node:os";
import path from "node:path";
import { after, test } from "node:test";

const dir = mkdtempSync(path.join(os.tmpdir(), "okaychat-n8n-store-"));
process.env.OKAYCHAT_DATA_DIR = dir;
process.env.OKAYCHAT_SECRET = "store-test-secret-that-is-at-least-32-characters";
const { db } = await import("../db.js");
const store = await import("./store.js");
const config = { webhookUrl: "https://agent.example.test/hook?secret=query-secret", protocol: "webhook" as const, memoryMode: "history" as const, inputKey: "message", sessionKey: "sessionId", historyKey: "history", responseMode: "auto" as const, responsePointer: null, timeoutMs: 120000, idleTimeoutMs: 60000 };
const input = { name: "Probe", description: "", avatar: "workflow", enabled: true, config, authHeader: { name: "Authorization", value: "Bearer header-secret" } };
after(() => { db.close(); rmSync(dir, { recursive: true, force: true }); });
test("agent config is encrypted, round trips, enforces CAS and keeps run history on deletion", () => {
    db.prepare("INSERT INTO users (id,email,name,password_hash,role,created_at) VALUES (?,?,?,?,?,?)").run("u1", "u1@test", "User", "x", "user", 1);
    const agent = store.createAgent({ kind: "own", userId: "u1" }, input);
    const ciphertext = db.prepare("SELECT config_enc FROM n8n_agents WHERE id=?").get(agent.id) as { config_enc: string };
    assert.equal(ciphertext.config_enc.includes("query-secret"), false);
    assert.equal(ciphertext.config_enc.includes("header-secret"), false);
    assert.equal(store.getAgentDetail({ kind: "own", userId: "u1" }, agent.id).authHeader?.configured, true);
    assert.throws(() => store.updateAgent({ kind: "own", userId: "u1" }, agent.id, 9, input), /changed elsewhere/);
    const updated = store.updateAgent({ kind: "own", userId: "u1" }, agent.id, 1, { ...input, authHeader: null });
    assert.equal(updated.revision, 2);
    assert.equal(updated.authHeader, null);
    assert.equal(store.resolveAgent("u1", agent.id)?.config.authHeader, null);
    store.recordRun({ id: "run1", userId: "u1", threadId: null, agentId: agent.id, status: "ok", durationMs: 1, inputBytes: 1, outputBytes: 1 });
    store.deleteAgent({ kind: "own", userId: "u1" }, agent.id, 2);
    assert.equal(store.agentUsage("u1").runs, 1);
});

test('audiences include selected users and groups, including empty selections and admin use restrictions', async () => {
  const { createGroup, setAudience } = await import('../groups.js');
  for (const [id, role] of [['admin', 'admin'], ['viewer', 'user'], ['foreign', 'user']]) db.prepare('INSERT INTO users (id,email,name,password_hash,role,created_at) VALUES (?,?,?,?,?,?)').run(id!, `${id}@test`, id!, 'x', role!, 1);
  const group = createGroup('Viewers', ['viewer']);
  const agent = store.createAgent({ kind: 'shared', adminId: 'admin' }, { ...input, audience: { mode: 'selected', userIds: [], groupIds: [] } });
  assert.equal(store.resolveAgent('admin', agent.id), null);
  assert.equal(store.resolveAgent('viewer', agent.id), null);
  assert.ok(store.getAgentDetail({ kind: 'shared', adminId: 'admin' }, agent.id));
  assert.throws(() => store.getAgentDetail({ kind: 'shared', adminId: 'viewer' }, agent.id), { code: 'forbidden' });
  setAudience('n8n', agent.id, { mode: 'selected', userIds: [], groupIds: [group.id] });
  assert.ok(store.resolveAgent('viewer', agent.id));
  assert.equal(store.resolveAgent('foreign', agent.id), null);
  assert.throws(() => store.getAgentDetail({ kind: 'own', userId: 'viewer' }, agent.id), { code: 'not_found' });
  const listed = store.listVisibleAgents('viewer');
  assert.equal(listed[0]?.canManage, false);
  assert.doesNotMatch(JSON.stringify(listed), /query-secret|header-secret|webhookUrl/);
  const controller = new AbortController();
  const unregister = store.registerAgentRun({ viewerId: 'viewer', agentId: agent.id, revision: 1, threadId: null, controller });
  setAudience('n8n', agent.id, { mode: 'selected', userIds: [], groupIds: [] });
  assert.equal(controller.signal.aborted, true);
  unregister();
  db.prepare('DELETE FROM users WHERE id=?').run('admin');
  assert.equal(db.prepare("SELECT 1 FROM share_audiences WHERE kind='n8n' AND resource_id=?").get(agent.id), undefined);
});

test('credential retention requires identical destination, sessions are encrypted and quota growth is atomic', async () => {
  const { ensureThread } = await import('../threads.js');
  const { storageUsed } = await import('../quota.js');
  const { authHeader: _secret, ...withoutSecret } = input;
  const agent = store.createAgent({ kind: 'own', userId: 'u1' }, input);
  const kept = store.updateAgent({ kind: 'own', userId: 'u1' }, agent.id, 1, withoutSecret);
  assert.equal(store.resolveAgent('u1', agent.id)?.config.authHeader?.value, input.authHeader.value);
  assert.throws(() => store.updateAgent({ kind: 'own', userId: 'u1' }, agent.id, kept.revision, { ...withoutSecret, config: { ...config, webhookUrl: 'https://changed.example.test' } }), { code: 'validation' });
  ensureThread('u1', 'thread');
  const before = storageUsed('u1');
  assert.equal(store.saveSession('u1', 'thread', agent.id, kept.revision, 'opaque-session-secret', 'digest'), true);
  assert.equal(store.getSession('u1', 'thread', agent.id)?.sessionId, 'opaque-session-secret');
  assert.doesNotMatch(JSON.stringify(db.prepare('SELECT * FROM n8n_agent_sessions').all()), /opaque-session-secret/);
  assert.ok(storageUsed('u1') > before);
  assert.equal(store.saveSession('foreign', 'thread', agent.id, kept.revision, 'no', 'no'), false);
  store.updateAgent({ kind: 'own', userId: 'u1' }, agent.id, kept.revision, withoutSecret);
  assert.equal(store.getSession('u1', 'thread', agent.id), null);
  db.prepare('UPDATE users SET storage_limit=? WHERE id=?').run(storageUsed('u1'), 'u1');
  assert.throws(() => store.createAgent({ kind: 'own', userId: 'u1' }, input), { code: 'storage_quota' });
  assert.equal(store.listOwnedAgents('u1').length, 1);
  db.prepare('UPDATE users SET storage_limit=NULL WHERE id=?').run('u1');
  const ciphertext = db.prepare('SELECT config_enc FROM n8n_agents WHERE id=?').get(agent.id) as { config_enc: string };
  db.prepare('UPDATE n8n_agents SET config_enc=? WHERE id=?').run(ciphertext.config_enc.slice(0, -5) + 'xxxxx', agent.id);
  assert.throws(() => store.resolveAgent('u1', agent.id), { code: 'unknown' });
  store.deleteAgent({ kind: 'own', userId: 'u1' }, agent.id, 3);
});
