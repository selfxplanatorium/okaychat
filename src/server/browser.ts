import { randomBytes } from "node:crypto";
import { mkdirSync, readFileSync, renameSync, writeFileSync } from "node:fs";
import path from "node:path";
import type { Health } from "../browser/api.js";

// Client for the browser worker (src/browser/, its own container in compose). The app keeps every ownership
// check: it looks the bytes up, sends them with a fixed job type, and gets the result on the same request.
// See docs/research/browser-worker.md.

// Read when used, not at import: render helpers import this module, and tests start a worker after importing them.
// `npm run dev` points OKAYCHAT_DEV_BROWSER_URL at its local worker unless .env names another (scripts/dev-browser.sh).
const browserUrl = () => (process.env.OKAYCHAT_BROWSER_URL ?? process.env.OKAYCHAT_DEV_BROWSER_URL ?? "").replace(/\/+$/, "");
const tokenFile = () => path.resolve(process.env.OKAYCHAT_BROWSER_TOKEN_FILE ?? path.join(process.env.OKAYCHAT_DATA_DIR ?? "./data", "browser-token"));

let token: string | null = null;

/**
 * The worker's bearer token. Generated by the app on first start into a file only the worker also mounts,
 * so neither compose nor .env needs another secret. The file holds nothing else. It authorizes render and fetch
 * jobs on the worker, nothing in the app.
 */
export function browserToken(): string {
  if (token) return token;
  try {
    const existing = readFileSync(tokenFile(), "utf8").trim();
    if (existing.length >= 32) return (token = existing);
  } catch {
    // Created below.
  }
  const fresh = randomBytes(32).toString("base64url");
  const file = tokenFile();
  mkdirSync(path.dirname(file), { recursive: true });
  // Group-readable: in compose the directory is setgid to the worker's job API group (docker-entrypoint.sh), so
  // that user can read the token and the worker's browser users cannot.
  const temporary = `${file}.${process.pid}`;
  writeFileSync(temporary, `${fresh}\n`, { mode: 0o640 });
  renameSync(temporary, file);
  return (token = fresh);
}

export const browserConfigured = () => !!browserUrl();

/** Thrown when the worker refuses a job for a reason the model can act on (for example a page number). */
export class BrowserJobError extends Error {
  constructor(
    message: string,
    readonly forModel: boolean,
  ) {
    super(message);
  }
}

export async function browserJob<T>(route: string, body: unknown, timeoutMs: number, signal?: AbortSignal): Promise<T> {
  if (!browserConfigured()) throw new BrowserJobError("The browser worker is not configured on this server (OKAYCHAT_BROWSER_URL).", false);
  const timeout = AbortSignal.timeout(timeoutMs);
  let res: Response;
  try {
    res = await fetch(`${browserUrl()}${route}`, {
      method: "POST",
      headers: { "Content-Type": "application/json", Authorization: `Bearer ${browserToken()}` },
      body: JSON.stringify(body),
      signal: signal ? AbortSignal.any([signal, timeout]) : timeout,
    });
  } catch (error) {
    if (signal?.aborted) throw new Error("Cancelled.");
    console.error("browser worker request failed:", (error as Error).message);
    throw new BrowserJobError(timeout.aborted ? "The browser worker did not answer in time." : "The browser worker is not reachable.", false);
  }
  const value = (await res.json().catch(() => ({}))) as T & { error?: string; model?: boolean };
  if (!res.ok) throw new BrowserJobError(value.error ?? `The browser worker failed (${res.status}).`, !!value.model);
  return value;
}

let health: { value: Health | null; at: number } = { value: null, at: 0 };

/** The worker's last reported health, refreshed in the background at most every 30 s. */
export function browserHealth(): Health | null {
  if (browserConfigured() && Date.now() - health.at > 30_000) {
    health = { ...health, at: Date.now() };
    void fetch(`${browserUrl()}/health`, { signal: AbortSignal.timeout(3000) })
      .then((r) => r.json() as Promise<Health>)
      .then(
        (value) => (health = { value, at: Date.now() }),
        () => (health = { value: null, at: Date.now() }),
      );
  }
  return health.value;
}
