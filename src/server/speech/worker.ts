import { randomBytes } from "node:crypto";
import { mkdirSync, readFileSync, renameSync, writeFileSync } from "node:fs";
import path from "node:path";
import { HTTPException } from "hono/http-exception";
import { USER_AGENT } from "../env.js";

// Client for the speech worker (speech/, its own container in compose): faster-whisper and Piper, on the CPU
// or an optional NVIDIA GPU. Audio and text only pass through it in memory. See docs/implementation/speech.md.

// Read when used, not at import, so tests can start a fake worker after importing this module.
const workerUrl = () => (process.env.OKAYCHAT_SPEECH_URL ?? "").replace(/\/+$/, "");
const tokenFile = () => path.resolve(process.env.OKAYCHAT_SPEECH_TOKEN_FILE ?? path.join(process.env.OKAYCHAT_DATA_DIR ?? "./data", "speech-token"));

let token: string | null = null;

/**
 * The worker's bearer token, generated by the app on first start into a volume only the worker also mounts,
 * so compose needs no extra secret. It authorizes speech jobs on the worker and nothing in the app.
 */
export function speechToken(): string {
  if (token) return token;
  if ((process.env.OKAYCHAT_SPEECH_TOKEN ?? "").length >= 32) return (token = process.env.OKAYCHAT_SPEECH_TOKEN!);
  try {
    const existing = readFileSync(tokenFile(), "utf8").trim();
    if (existing.length >= 32) return (token = existing);
  } catch {
    // Created below.
  }
  const fresh = randomBytes(32).toString("base64url");
  const file = tokenFile();
  mkdirSync(path.dirname(file), { recursive: true });
  const temporary = `${file}.${process.pid}`;
  // Group-readable: in compose the directory is setgid to the speech worker's group (docker-entrypoint.sh).
  writeFileSync(temporary, `${fresh}\n`, { mode: 0o640 });
  renameSync(temporary, file);
  return (token = fresh);
}

export const speechWorkerConfigured = () => !!workerUrl();

async function call(pathAndQuery: string, init: { method?: string; body?: BodyInit; contentType?: string; timeoutMs: number; signal?: AbortSignal }): Promise<Response> {
  if (!speechWorkerConfigured()) throw new HTTPException(400, { message: "This server has no speech worker." });
  const signal = init.signal ? AbortSignal.any([init.signal, AbortSignal.timeout(init.timeoutMs)]) : AbortSignal.timeout(init.timeoutMs);
  let res: Response;
  try {
    res = await fetch(`${workerUrl()}${pathAndQuery}`, {
      method: init.method ?? "GET",
      body: init.body,
      headers: { Authorization: `Bearer ${speechToken()}`, "User-Agent": USER_AGENT, ...(init.contentType ? { "Content-Type": init.contentType } : {}) },
      signal,
    });
  } catch (error) {
    if (init.signal?.aborted) throw error;
    throw new HTTPException(502, { message: (error as Error).name === "TimeoutError" ? "The speech worker timed out." : "The speech worker is not reachable." });
  }
  if (!res.ok) {
    const message = ((await res.json().catch(() => null)) as { error?: string } | null)?.error ?? `The speech worker answered ${res.status}.`;
    throw new HTTPException(res.status === 413 ? 413 : res.status === 503 ? 503 : 502, { message: message.slice(0, 300) });
  }
  return res;
}

export async function workerTranscribe(
  audio: Uint8Array,
  options: { model: string; language?: string; vad: boolean; maxSeconds: number },
  signal?: AbortSignal,
): Promise<{ text: string; language?: string }> {
  const q = new URLSearchParams({ model: options.model, vad: options.vad ? "1" : "0", max_seconds: String(options.maxSeconds) });
  if (options.language) q.set("language", options.language);
  // A cold start downloads the model first; large models take minutes on a slow link.
  const res = await call(`/transcribe?${q}`, { method: "POST", body: audio as Uint8Array<ArrayBuffer>, contentType: "application/octet-stream", timeoutMs: 15 * 60_000, signal });
  return (await res.json()) as { text: string; language?: string };
}

export async function workerSpeak(text: string, options: { voice: string; speed: number }, signal?: AbortSignal): Promise<Uint8Array> {
  const q = new URLSearchParams({ voice: options.voice, speed: String(options.speed) });
  const res = await call(`/speak?${q}`, { method: "POST", body: text, contentType: "text/plain; charset=utf-8", timeoutMs: 5 * 60_000, signal });
  return new Uint8Array(await res.arrayBuffer());
}

export async function workerVoices(): Promise<Array<{ id: string; name: string; language: string }>> {
  const res = await call("/voices", { timeoutMs: 30_000 });
  return ((await res.json()) as { voices: Array<{ id: string; name: string; language: string }> }).voices;
}

export async function workerModels(): Promise<{ models: string[]; downloaded: string[] }> {
  return (await (await call("/models", { timeoutMs: 10_000 })).json()) as { models: string[]; downloaded: string[] };
}

/** Starts a model download in the worker so the first real request does not wait for it. */
export async function workerPreload(kind: "stt" | "tts", name: string): Promise<void> {
  await call(`/preload?${new URLSearchParams({ kind, name })}`, { method: "POST", timeoutMs: 10_000 });
}

/** The worker's health. Device fields are optional so an older worker payload still reads. */
export interface WorkerHealth {
  ok: boolean;
  stt: boolean;
  tts: boolean;
  requestedDevice?: "auto" | "cpu" | "cuda";
  device?: "cpu" | "cuda";
  computeType?: string | null;
  gpuName?: string | null;
  cudaVersion?: string | null;
  cudaAvailable?: boolean | null;
  degraded?: boolean;
  reason?: string | null;
  model?: string | null;
}

export async function workerHealth(): Promise<WorkerHealth | null> {
  if (!speechWorkerConfigured()) return null;
  try {
    const res = await fetch(`${workerUrl()}/health`, { signal: AbortSignal.timeout(3000) });
    return res.ok ? ((await res.json()) as WorkerHealth) : null;
  } catch {
    return null;
  }
}
