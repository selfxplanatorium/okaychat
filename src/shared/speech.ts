/** Server-wide speech settings, set by an admin. */
export interface AdminSpeechSettings {
  /** Hours a recording is kept after transcription. 0 keeps nothing: audio exists only during the request. */
  retentionHours: number;
  /** Longest recording accepted, in seconds. */
  maxRecordingSeconds: number;
  local: {
    stt: boolean;
    tts: boolean;
    /** faster-whisper model name. */
    whisperModel: string;
    /** Skip silence before transcribing (Silero VAD). */
    vad: boolean;
    defaultVoice: string;
  };
}

