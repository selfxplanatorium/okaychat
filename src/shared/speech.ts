export const speechConnectionId = (service: SpeechKeyService) => `speech-${service}`;

export interface SpeechEngineDef<Id extends string> {
  id: Id;
  name: string;
  credential: SpeechCredential;
  /** Built-in models, default first. Empty when the engine has no model choice. */
  models: string[];
  /** Model ids may be typed freely (self-hosted servers). */
  freeModel?: boolean;
  note?: string;
}

export interface TtsEngineDef extends SpeechEngineDef<TtsEngineId> {
  /** Built-in voices, default first. Engines with a live voice list load it instead. */
  voices: string[];
  freeVoice?: boolean;
  /** Accepts a style instruction ("calm, slow, warm"). */
  instructions?: boolean;
}

