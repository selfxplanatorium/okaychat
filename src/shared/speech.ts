export interface SpeechEngineStatus {
  id: string;
  name: string;
  credential: SpeechCredential;
  /** Usable now: key present, worker reachable, or browser engine. */
  ready: boolean;
  /** The key comes from an admin's server-wide connection. */
  shared: boolean;
  /** Why it is not ready, for the settings page. */
  reason?: string;
}

export interface SpeechStatus {
  stt: SpeechEngineStatus[];
  tts: SpeechEngineStatus[];
  /** Saved speech-only keys (never the secret itself). */
  keys: Partial<Record<SpeechKeyService, { connected: boolean; shared: boolean; region?: string; baseURL?: string }>>;
  retentionHours: number;
  maxRecordingSeconds: number;
  /** The local worker is configured on this server. */
  worker: boolean;
  /** The admin's default Piper voice, used until the user picks one. */
  localVoice: string;
}

export interface SpeechOption {
  id: string;
  name?: string;
  language?: string;
}

export interface SpeechOptionList {
  options: SpeechOption[];
  /** False when the built-in list is shown because the provider has no list endpoint or failed. */
  live: boolean;
  error?: string;
}
