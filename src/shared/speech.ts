export type SttEngineId = "browser" | "local" | "openai" | "groq" | "mistral" | "azure" | "deepgram" | "elevenlabs" | "openai-compatible";
export type TtsEngineId = "local" | "browser" | "openai" | "openai-realtime" | "azure" | "elevenlabs" | "mistral" | "openai-compatible";

/** Where an engine's credential comes from. */
export type SpeechCredential =
  /** Runs in the browser. Nothing reaches the server. */
  | { type: "browser" }
  /** The server's own speech worker. */
  | { type: "local" }
  /** The chat provider connection of this id: one key covers chat and speech. */
  | { type: "provider"; providerId: string }
  /** A key saved only for speech, stored as provider connection `speech-<service>`. */
  | { type: "own"; service: SpeechKeyService };

/** Services whose speech keys are saved separately from chat providers. */
export type SpeechKeyService = "azure" | "deepgram" | "elevenlabs" | "compatible-stt" | "compatible-tts";

