export type TtsSplit = "sentence" | "paragraph" | "none";

/** Per-account speech preferences. Engines remember their own model and voice, so switching back keeps them. */
export interface SpeechSettings {
  stt?: {
    engine?: SttEngineId | "off";
    /** ISO 639-1 code; empty lets the engine detect it. */
    language?: string;
    /** Stop recording after this many seconds of silence. 0 records until stopped. */
    silenceSeconds?: number;
    models?: Partial<Record<SttEngineId, string>>;
  };
  tts?: {
    engine?: TtsEngineId | "off";
    /** Read each finished reply aloud. */
    autoPlay?: boolean;
    /** 0.5–2. */
    speed?: number;
    /** How replies are cut into requests: smaller pieces start playing sooner. */
    split?: TtsSplit;
    models?: Partial<Record<TtsEngineId, string>>;
    voices?: Partial<Record<TtsEngineId, string>>;
    /** Style instruction for engines that take one. */
    instructions?: string;
  };
  /** Voice calls. See docs/implementation/voice-calls.md. */
  call?: CallSettings;
}

